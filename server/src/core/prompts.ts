/**
 * 返回当前生效的提示词配置：用户覆盖（system-config.json 的 prompts）覆盖默认值，未覆盖项回退到 PROMPT_DEFAULTS。
 */
export function getPromptConfig(): PromptConfig {
  const overrides = (getSystemConfig() as { prompts?: Partial<PromptConfig> }).prompts;
  if (!overrides) {
    return PROMPT_DEFAULTS;
  }
  return {
    ...PROMPT_DEFAULTS,
    ...overrides,
    sceneHints: {
      ...PROMPT_DEFAULTS.sceneHints,
      ...(overrides.sceneHints || {})
    }
  };
}
